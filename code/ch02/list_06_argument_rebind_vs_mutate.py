"""リスト2-6: 引数の「再束縛」と「変更」は呼び出し元への影響が違う。

Pythonの引数渡しは値渡し・参照渡しのどちらとも異なり、しばしば
「オブジェクトの共有渡し」と呼ばれる。関数内で仮引数名を新しい
オブジェクトへ再束縛しても呼び出し元には影響しないが、同じ
オブジェクトを変更（ミューテート）すれば呼び出し元からも見える。
"""


def rebind_only(value: int) -> int:
    """仮引数を新しいintへ再束縛するだけで、呼び出し元には影響しない。"""
    value = value + 1
    return value


def mutate_in_place(values: list) -> None:
    """同じlistオブジェクトを変更するため、呼び出し元にも影響する。"""
    values.append(99)
